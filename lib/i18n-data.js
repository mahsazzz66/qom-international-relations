const LOWER = {};
Object.keys(T).forEach(k => { LOWER[k.toLowerCase()] = T[k]; });
const FLIP = { '\u2190': '\u2192', '\u2192': '\u2190' };

function lookup(key, lang) {
  const e = T[key] || LOWER[key.toLowerCase()];
  return e && e[lang] ? e[lang] : null;
}

export function translate(text, lang) {
  if (lang === 'en') return null;
  const key = text.trim();
  if (!key) return null;
  const hit = lookup(key, lang);
  if (hit) return text.replace(key, hit);
  const m = key.match(/^([^0-9A-Za-z\u0600-\u06FF]*)(.*?)([^0-9A-Za-z\u0600-\u06FF]*)$/);
  if (m && m[2] && m[2] !== key) {
    const core = lookup(m[2].trim(), lang);
    if (core) {
      const pre = m[1].replace(/[\u2190\u2192]/g, c => FLIP[c]);
      const post = m[3].replace(/[\u2190\u2192]/g, c => FLIP[c]);
      return text.replace(key, pre + core + post);
    }
  }
  return null;
}
